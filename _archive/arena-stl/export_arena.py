"""
Exports the ARENA collection (built by build_arena.py) to js/mesh-testarena.js in game coordinates:
   x = (X - 8) * 0.12,  y = (Z - 20) * 0.12,  z = -(Y + 26) * 0.12      (Blender X, Y, Z = the STL's X, Y, Z-up)
pos = 9 numbers per triangle, nor = 3 per triangle (outward), col = palette index per triangle. Run inside Blender.
"""
import bpy, bmesh, json

OUT = r'C:\Users\ryder\Downloads\Rivel\js\mesh-testarena.js'
S, XC, YC = 0.12, 8.0, -26.0
PALETTE = {'greyMid': 0xa9aeb8, 'greyLight': 0xc3c8d1, 'grey': 0x9399a4, 'greyDark': 0x767b86}
names = list(PALETTE)


def T(v):
    return ((v.x - XC) * S, (v.z - 20.0) * S, -(v.y - YC) * S)


col = bpy.data.collections['ARENA']
dg = bpy.context.evaluated_depsgraph_get()
pos, nor, cidx = [], [], []
for ob in col.objects:
    if ob.type != 'MESH':
        continue
    eo = ob.evaluated_get(dg)
    me = eo.to_mesh()
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    mats = [s.material.name[3:] if s.material else 'grey' for s in ob.material_slots]
    mw = ob.matrix_world
    for f in bm.faces:
        mname = mats[f.material_index] if f.material_index < len(mats) else mats[0]
        if mname not in PALETTE:
            mname = 'grey'
        a, b, c = [T(mw @ v.co) for v in f.verts]
        # skip degenerate slivers
        e1 = (b[0] - a[0], b[1] - a[1], b[2] - a[2])
        e2 = (c[0] - a[0], c[1] - a[1], c[2] - a[2])
        cx = (e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0])
        ln = (cx[0] ** 2 + cx[1] ** 2 + cx[2] ** 2) ** 0.5
        if ln < 1e-9:
            continue
        # game-space normal from the winding (the transform is a proper rotation, so outward stays outward)
        n = (cx[0] / ln, cx[1] / ln, cx[2] / ln)
        for p in (a, b, c):
            pos.extend(round(x, 3) + 0.0 for x in p)
        nor.extend(round(x, 2) + 0.0 for x in n)
        cidx.append(names.index(mname))
    bm.free()
    eo.to_mesh_clear()

js = (
    '/* GENERATED by tools/blender/export_arena.py from the Blender arena (see _models/dashduel-models.blend; the shape is the CC0\n'
    ' * "Rivals Arena Map" STL). Do not edit. Triangles in game coordinates; col = index into palette. */\n'
    '(function () {\n  const RV = (window.RV = window.RV || {});\n  RV.meshes = RV.meshes || {};\n  RV.meshes.testarena = '
    + json.dumps({'scale': S, 'xc': XC, 'yc': YC, 'palette': [PALETTE[k] for k in names], 'pos': pos, 'nor': nor, 'col': cidx}, separators=(',', ':'))
    + ';\n})();\n'
)
open(OUT, 'w', encoding='utf-8').write(js)
result = {'tris': len(cidx), 'bytes': len(js)}
