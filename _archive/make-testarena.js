'use strict';
/*
 * Converts _models/rivals-arena-map.stl (CC0 "Rivals Arena Map" from Printables) into js/mesh-testarena.js: the exact
 * triangles of the model, in game coordinates (metres, +Y up), with outward-facing normals.
 *
 *   node tools/make-testarena.js
 *
 * Model axes are (X, Y, Z-up) in millimetre-ish units; the arena floor is at Z = 20 and the model's centre is
 * (XC, YC) = (8, -26). Game coordinates:  x = (X - XC) * S,  y = (Z - 20) * S,  z = -(Y - YC) * S  (a proper rotation,
 * so the map is not mirrored). The collision shapes in js/maps.js use the same numbers and the same transform.
 */
const fs = require('fs');
const path = require('path');
const S = 0.12,
  XC = 8,
  YC = -26;
const buf = fs.readFileSync(path.join(__dirname, '..', '_models', 'rivals-arena-map.stl'));
const count = buf.readUInt32LE(80);
const T = (X, Y, Z) => [(X - XC) * S, (Z - 20) * S, -(Y - YC) * S];
const tris = [];
for (let i = 0; i < count; i++) {
  const o = 84 + i * 50;
  const v = [];
  for (let k = 0; k < 3; k++) v.push(T(buf.readFloatLE(o + 12 + k * 12), buf.readFloatLE(o + 16 + k * 12), buf.readFloatLE(o + 20 + k * 12)));
  tris.push(v);
}
const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const norm = (a) => {
  const l = Math.hypot(a[0], a[1], a[2]) || 1;
  return [a[0] / l, a[1] / l, a[2] / l];
};
// Moller-Trumbore: distance along the ray to the triangle, or -1
function hit(o, d, t) {
  const e1 = sub(t[1], t[0]),
    e2 = sub(t[2], t[0]);
  const p = cross(d, e2);
  const det = dot(e1, p);
  if (Math.abs(det) < 1e-12) return -1;
  const inv = 1 / det;
  const s = sub(o, t[0]);
  const u = dot(s, p) * inv;
  if (u < 0 || u > 1) return -1;
  const q = cross(s, e1);
  const v = dot(d, q) * inv;
  if (v < 0 || u + v > 1) return -1;
  const dist = dot(e2, q) * inv;
  return dist > 1e-6 ? dist : -1;
}
// outward normal: the side from which a ray escapes the solid (even number of crossings)
let flipped = 0;
const out = [];
for (let i = 0; i < tris.length; i++) {
  const t = tris[i];
  let n = norm(cross(sub(t[1], t[0]), sub(t[2], t[0])));
  const c = [(t[0][0] + t[1][0] + t[2][0]) / 3, (t[0][1] + t[1][1] + t[2][1]) / 3, (t[0][2] + t[1][2] + t[2][2]) / 3];
  let votes = 0;
  for (const j of [[0.0123, 0.0071, 0.0042], [-0.0091, 0.0057, 0.0133], [0.0033, -0.0117, 0.0081]]) {
    const d = norm([n[0] + j[0], n[1] + j[1], n[2] + j[2]]);
    const o = [c[0] + n[0] * 1e-3, c[1] + n[1] * 1e-3, c[2] + n[2] * 1e-3];
    let crossings = 0;
    for (let k = 0; k < tris.length; k++) if (k !== i && hit(o, d, tris[k]) > 0) crossings++;
    votes += crossings % 2 === 0 ? 1 : -1; // even = n points out of the solid
  }
  if (votes < 0) {
    n = [-n[0], -n[1], -n[2]];
    flipped++;
  }
  out.push({ t, n });
}
const r = (v) => Math.round(v * 1000) / 1000;
const pos = [],
  nor = [];
for (const { t, n } of out) {
  // wind counter-clockwise seen from outside (so back-face culling and shading agree)
  const w = norm(cross(sub(t[1], t[0]), sub(t[2], t[0])));
  const verts = dot(w, n) >= 0 ? t : [t[0], t[2], t[1]];
  for (const v of verts) pos.push(r(v[0]), r(v[1]), r(v[2]));
  nor.push(r(n[0]), r(n[1]), r(n[2]));
}
const js =
  '/* GENERATED by tools/make-testarena.js from _models/rivals-arena-map.stl (CC0 "Rivals Arena Map"). Do not edit.\n' +
  ' * The exact triangles of the model in game coordinates; pos = 9 numbers per triangle, nor = 3 per triangle (outward). */\n' +
  '(function () {\n  const RV = (window.RV = window.RV || {});\n  RV.meshes = RV.meshes || {};\n  RV.meshes.testarena = { scale: ' + S + ', xc: ' + XC + ', yc: ' + YC + ', pos: ' + JSON.stringify(pos) + ', nor: ' + JSON.stringify(nor) + ' };\n})();\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'mesh-testarena.js'), js);
console.log('triangles', tris.length, 'normals flipped', flipped, 'bytes', js.length);
