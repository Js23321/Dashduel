"""
Exports the DASHDUEL weapon collections (WEAPON_rifle, WEAPON_pistol, WEAPON_grenade, WEAPON_hands) to
js/models-weapons.js: triangles in GAME coordinates, grouped by part (body + animated parts, positions relative to the
part's pivot) and by material NAME (the game maps names to its own materials). Run inside Blender.
"""
import bpy, bmesh, json

OUT = r'C:\Users\ryder\Downloads\Rivel\js\models-weapons.js'
MODELS = {'rifle': 'WEAPON_rifle', 'pistol': 'WEAPON_pistol', 'grenade': 'WEAPON_grenade'}  # (the hands are block fists built in js/viewmodel.js; WEAPON_hands is no longer exported)


def r4(v):
    v = round(v, 4)
    return 0.0 if v == 0 else v


def export_collection(col, depsgraph):
    parts = {}
    for ob in col.objects:
        if ob.type != 'MESH':
            continue
        part = ob.get('part', 'body')
        pv = [float(x) for x in col.get('pivot_' + part, (0, 0, 0))]
        eo = ob.evaluated_get(depsgraph)
        me = eo.to_mesh()
        bm = bmesh.new()
        bm.from_mesh(me)
        bmesh.ops.triangulate(bm, faces=bm.faces[:])
        mw = ob.matrix_world
        m3 = mw.to_3x3()
        mat = ob.material_slots[0].material.name[3:] if ob.material_slots else 'grey'
        P = parts.setdefault(part, {'pivot': [r4(v) for v in pv], 'mats': {}})
        M = P['mats'].setdefault(mat, {'p': [], 'n': [], 'i': [], '_k': {}})
        for f in bm.faces:
            n = (m3 @ f.normal).normalized()
            ng = (n.x, n.z, -n.y)  # blender -> game
            idx = []
            for v in f.verts:
                w = mw @ v.co
                gp = (w.x - pv[0], w.z - pv[1], -w.y - pv[2])
                key = (r4(gp[0]), r4(gp[1]), r4(gp[2]), round(ng[0], 2), round(ng[1], 2), round(ng[2], 2))
                j = M['_k'].get(key)
                if j is None:
                    j = len(M['p']) // 3
                    M['_k'][key] = j
                    M['p'].extend(key[:3])
                    M['n'].extend(key[3:])
                idx.append(j)
            M['i'].extend(idx)
        bm.free()
        eo.to_mesh_clear()
    for P in parts.values():
        for M in P['mats'].values():
            del M['_k']
    return parts


def run():
    dg = bpy.context.evaluated_depsgraph_get()
    out = {}
    info = {}
    for key, cname in MODELS.items():
        col = bpy.data.collections.get(cname)
        if not col:
            continue
        parts = export_collection(col, dg)
        out[key] = {'parts': parts}
        info[key] = {p: sum(len(M['i']) // 3 for M in P['mats'].values()) for p, P in parts.items()}
    js = (
        '/* GENERATED by tools/blender/export_models.py from the Blender models (see _models/dashduel-models.blend). Do not edit.\n'
        ' * Weapon / hand / grenade models: triangles in game coordinates (y up, muzzle at -z), by part (body + animated parts,\n'
        ' * positions relative to the part pivot) and by material name. p = positions, n = normals, i = triangle indices. */\n'
        '(function () {\n  const RV = (window.RV = window.RV || {});\n  RV.models = RV.models || {};\n  Object.assign(RV.models, '
        + json.dumps(out, separators=(',', ':'))
        + ');\n})();\n'
    )
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(js)
    return {'bytes': len(js), 'tris': info}


result = run()
